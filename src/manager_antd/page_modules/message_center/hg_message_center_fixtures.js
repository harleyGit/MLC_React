const MINUTE = 60 * 1000;
const HOUR = 60 * MINUTE;

/** 生成相对当前时间的时间戳，保证示例数据的“今天/昨天”分组始终有效。 */
const minutesAgo = (minutes) => new Date(Date.now() - minutes * MINUTE).toISOString();

/** 生成相对当前时间的小时级时间戳，用于更早的会话与通知。 */
const hoursAgo = (hours) => new Date(Date.now() - hours * HOUR).toISOString();

